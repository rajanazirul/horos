// Regenerates src/generated/policy-wallet-artifact.ts from the Foundry artifact (contracts/out, gitignored): the ABI,
// the creation bytecode, and the expected runtime codehash (keccak256 of `deployedBytecode`, which equals the
// on-chain codehash because the only immutable, `roleIsContract`, is false and so stays zero). Run `forge build`
// first. CI regenerates it after `forge build` and fails on a diff (Story 3.2).
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const artifactUrl = new URL("../../../contracts/out/PolicyWallet.sol/PolicyWallet.json", import.meta.url);
const fixtureUrl = new URL("../../../fixtures/horos-demo-wallet.json", import.meta.url);
const outUrl = new URL("../src/generated/policy-wallet-artifact.ts", import.meta.url);

let artifact;
try {
  artifact = JSON.parse(readFileSync(artifactUrl, "utf8"));
} catch (err) {
  console.error(`cannot read ${artifactUrl.pathname}; run \`forge build\` in contracts/ first (${String(err)})`);
  process.exit(1);
}
const hex = /^0x(?:[0-9a-f]{2})+$/;
const creation = artifact.bytecode?.object;
const runtime = artifact.deployedBytecode?.object;
if (!Array.isArray(artifact.abi) || typeof creation !== "string" || !hex.test(creation) || typeof runtime !== "string" || !hex.test(runtime)) {
  console.error("artifact needs an abi array and linked hex bytecode.object / deployedBytecode.object");
  process.exit(1);
}

// The fixture pins the codehash of the recorded Demo wallet. A contract change must update it deliberately, so a
// mismatch fails here without writing anything.
let fixtureCodehash;
try {
  fixtureCodehash = JSON.parse(readFileSync(fixtureUrl, "utf8")).codehash;
} catch (err) {
  console.error(`cannot read ${fixtureUrl.pathname} (${String(err)})`);
  process.exit(1);
}
if (typeof fixtureCodehash !== "string" || !/^0x[0-9a-f]{64}$/.test(fixtureCodehash)) {
  console.error(`${fixtureUrl.pathname} has no valid lowercase "codehash"`);
  process.exit(1);
}
const codehash = keccak256(runtime);
if (codehash !== fixtureCodehash) {
  // The metadata hash in the bytecode covers the remappings: a checkout with OpenZeppelin's nested submodules
  // initialised auto-detects extra remappings and builds different bytecode than CI.
  console.error(
    `runtime codehash ${codehash} differs from fixtures/horos-demo-wallet.json (${fixtureCodehash}); nothing written. ` +
      "If contracts/src changed, update the fixture deliberately. Otherwise check `forge remappings` for extra auto-detected " +
      "entries (e.g. from contracts/lib/openzeppelin-contracts/lib) and build without them.",
  );
  process.exit(1);
}

const text = `// GENERATED by \`pnpm --filter @horos/sdk artifact:generate\` from contracts/out/PolicyWallet.sol/PolicyWallet.json.
// Do not edit by hand; CI regenerates it after \`forge build\` and fails on a diff.
export const policyWalletAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** PolicyWallet creation bytecode (constructor args are ABI-encoded after it). */
export const policyWalletBytecode = "${creation}" as const;

/** keccak256 of the PolicyWallet runtime code: every correctly deployed PolicyWallet (roleIsContract = false) has this codehash. */
export const expectedRuntimeCodehash = "${codehash}" as const;
`;
writeFileSync(outUrl, text);
console.log(`wrote ${outUrl.pathname} (${artifact.abi.length} abi entries, codehash ${codehash})`);
